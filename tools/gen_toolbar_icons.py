#!/usr/bin/env python3
"""Renders the toolbar icons from VS Code's codicon font into src/vscode_toolbar_icons.h.

Run from the repo root: python3 tools/gen_toolbar_icons.py (needs Pillow).
"""
import io
import os

from PIL import Image, ImageDraw, ImageFont

FONT = os.path.join("cph_dist", "codicon.ttf")
COLOUR = (0xC5, 0xC5, 0xC5, 255)  # VS Code's icon.foreground in Dark+
SIZES = (16, 20, 24, 32, 48, 64)
ICONS = {  # name -> codicon code point (from codicon.css)
    "beaker": 0xEA79,
    "debug_alt": 0xEB91,
    "shield": 0xEB53,
    "eye": 0xEA70,
    "question": 0xEB32,
}


def render(code, size):
    font = ImageFont.truetype(FONT, size)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    left, top, right, bottom = draw.textbbox((0, 0), chr(code), font=font)
    x = (size - (right - left)) / 2 - left
    y = (size - (bottom - top)) / 2 - top
    draw.text((x, y), chr(code), font=font, fill=COLOUR)
    out = io.BytesIO()
    img.save(out, "PNG", optimize=True)
    return out.getvalue()


def main():
    lines = ["// Generated by tools/gen_toolbar_icons.py from cph_dist/codicon.ttf. Do not edit.",
             "#pragma once", "#include <cstddef>", "",
             "struct ToolbarIcon { const char *name; int size; const unsigned char *png; size_t len; };", ""]
    table = []
    for name, code in ICONS.items():
        for size in SIZES:
            data = render(code, size)
            var = f"icon_{name}_{size}"
            body = ", ".join(str(b) for b in data)
            lines.append(f"static const unsigned char {var}[] = {{ {body} }};")
            table.append(f'    {{ "{name}", {size}, {var}, sizeof({var}) }},')
    lines += ["", "static const ToolbarIcon kToolbarIcons[] = {"] + table + ["};", ""]
    with open(os.path.join("src", "vscode_toolbar_icons.h"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
